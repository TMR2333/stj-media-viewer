#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成国家/省份中文名映射 (Geo/PlaceNames.g.cs)。

数据来源：
* 国家中文名：i18n-iso-countries 的 zh 语言包（MIT 许可），同目录 country_zh.json。
* 中国省级行政区中文名：GeoNames admin1CodesASCII.txt 的 CN 代码（CC BY 4.0），
  在本脚本内维护 34 条 代码→中文 映射（数据稳定，不必每次下载）。

用途：OfflineGeocoder 返回 GeoPlace 时，Country 用中文国家名（"中国"/"日本"/"冰岛"…），
Province 对中国城市用中文省名；其他国家/地区暂保留 admin1 代码（缺省不误报）。

用法：
    python src/StjMediaViewer.Core/Geo/Data/tools/gen_reference.py
输出：Geo/PlaceNames.g.cs
"""

import json
import os
import sys

# GeoNames admin1 code（中国） → 中文省名。
# 来源：https://download.geonames.org/export/dump/admin1CodesASCII.txt 的 CN.* 行。
CHINA_PROVINCES = {
    "01": "安徽", "02": "浙江", "03": "江西", "04": "江苏", "05": "吉林",
    "06": "青海", "07": "福建", "08": "黑龙江", "09": "河南", "10": "河北",
    "11": "湖南", "12": "湖北", "13": "新疆", "14": "西藏", "15": "甘肃",
    "16": "广西", "18": "贵州", "19": "辽宁", "20": "内蒙古", "21": "宁夏",
    "22": "北京", "23": "上海", "24": "山西", "25": "山东", "26": "陕西",
    "28": "天津", "29": "云南", "30": "广东", "31": "海南", "32": "四川",
    "33": "重庆",
}


def load_countries(path: str) -> dict:
    if not os.path.isfile(path):
        print(f"[gen-reference] 缺少 {path}，跳过国家名生成（运行时将回退 ISO 代码）", file=sys.stderr)
        return {}
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    countries = data.get("countries") or {}
    # 只保留形如 "CN" 的两字母代码，且值非空。
    return {code.upper(): name.strip() for code, name in countries.items()
            if len(code) == 2 and isinstance(name, str) and name.strip()}


def csharp_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_csharp(out_path: str, countries: dict) -> None:
    lines = [
        "// <auto-generated>",
        "// 本文件由 Geo/Data/tools/gen_reference.py 生成，请勿手工修改。",
        "// 国家中文名：i18n-iso-countries zh 语言包（MIT）；省级中文名：GeoNames admin1CodesASCII（CC BY 4.0）。",
        f"// 国家 {len(countries)} 个；中国省级行政区 {len(CHINA_PROVINCES)} 个。",
        "// </auto-generated>",
        "",
        "namespace StjMediaViewer.Core.Geo;",
        "",
        "internal static class PlaceNames",
        "{",
        "    internal static readonly IReadOnlyDictionary<string, string> CountryNames =",
        "        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)",
        "        {",
    ]
    for code in sorted(countries):
        lines.append(f"            [{csharp_string(code)}] = {csharp_string(countries[code])},")
    lines.extend([
        "        };",
        "",
        "    /// <summary>中国省级行政区：GeoName admin1 code → 中文省名。</summary>",
        "    internal static readonly IReadOnlyDictionary<string, string> ChinaProvinceNames =",
        "        new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)",
        "        {",
    ])
    for code in sorted(CHINA_PROVINCES):
        lines.append(f"            [{csharp_string(code)}] = {csharp_string(CHINA_PROVINCES[code])},")
    lines.extend([
        "        };",
        "",
        "    /// <summary>ISO2 → 中文国家名；未知返回 null。</summary>",
        "    internal static string? CountryChinese(string? iso2) =>",
        "        !string.IsNullOrWhiteSpace(iso2) && CountryNames.TryGetValue(iso2.Trim(), out var name) ? name : null;",
        "",
        "    /// <summary>admin1 code → 中文省名（仅中国）；其他返回 null（调用方回退代码或原名）。</summary>",
        "    internal static string? Admin1Chinese(string? countryIso2, string? admin1) =>",
        "        string.Equals(countryIso2, \"CN\", StringComparison.OrdinalIgnoreCase) &&",
        "        !string.IsNullOrWhiteSpace(admin1) &&",
        "        ChinaProvinceNames.TryGetValue(admin1.Trim(), out var province) ? province : null;",
        "}",
        "",
    ])

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"[gen-reference] 已生成 {out_path}（{os.path.getsize(out_path)} 字节）")


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.dirname(here)
    country_json = os.path.join(here, "country_zh.json")
    out_path = os.path.join(data_dir, "PlaceNames.g.cs")
    countries = load_countries(country_json)
    write_csharp(out_path, countries)


if __name__ == "__main__":
    main()